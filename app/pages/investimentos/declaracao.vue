<section>
  <h1>Módulo 8 — Declaração de Imposto de Renda nos Investimentos</h1>

  <h2>Como informar seus investimentos corretamente e evitar problemas com a Receita Federal</h2>

  <p>
    Quando uma pessoa começa a investir, é comum achar que o trabalho termina ao escolher o investimento certo.
    Mas existe uma parte importante que vem depois: informar tudo corretamente à Receita Federal.
    Declarar investimentos não significa apenas pagar imposto. Significa mostrar ao governo como seu dinheiro está aplicado
    e quanto ele rendeu ao longo do ano.
  </p>

  <p>
    Mesmo quem não pagou imposto em determinado investimento pode ter a obrigação de declarar.
    Isso acontece porque a declaração também serve para registrar seu patrimônio, ou seja, aquilo que você possui.
    É como fazer um “raio-X” financeiro do seu ano.
  </p>

  <h3>O que é o Imposto de Renda</h3>
  <p>
    O Imposto de Renda (IR) é um tributo cobrado pelo governo sobre os ganhos das pessoas.
    Ele incide sobre salários, aposentadorias, aluguéis e também sobre os lucros obtidos em investimentos.
    Em alguns casos, o imposto é descontado automaticamente no momento do resgate (chamado de “imposto na fonte”).
    Em outros, o próprio investidor precisa calcular e pagar usando um documento chamado DARF.
  </p>

  <h3>Quem precisa declarar investimentos</h3>
  <p>
    Deve declarar quem se enquadra em pelo menos uma das situações abaixo:
  </p>
  <ul>
    <li>Quem teve renda anual acima do limite definido pela Receita Federal.</li>
    <li>Quem teve qualquer operação em bolsa de valores (ações, FIIs, ETFs).</li>
    <li>Quem possuía bens ou investimentos acima de determinado valor no fim do ano.</li>
    <li>Quem teve lucro com venda de investimentos, mesmo que pequeno.</li>
  </ul>

  <p>
    Mesmo pessoas que só investem em produtos considerados “simples”, como CDB ou Tesouro Direto,
    podem precisar declarar, dependendo do valor investido ou do perfil de renda.
  </p>

  <h3>Quais investimentos precisam ser declarados</h3>
  <p>
    Praticamente todos os investimentos entram na declaração, entre eles:
  </p>
  <ul>
    <li>CDB (Certificado de Depósito Bancário)</li>
    <li>Títulos do Tesouro Direto</li>
    <li>LCI e LCA</li>
    <li>Ações</li>
    <li>Fundos imobiliários (FIIs)</li>
    <li>ETFs</li>
    <li>Fundos de investimento</li>
    <li>Criptomoedas</li>
  </ul>

  <p>
    Alguns desses produtos são isentos de imposto sobre o rendimento, como LCI e LCA.
    Mesmo assim, eles devem aparecer na declaração, pois fazem parte do seu patrimônio.
  </p>

  <h3>Quais impostos existem sobre investimentos</h3>
  <p>
    O principal imposto é o Imposto de Renda, mas ele funciona de formas diferentes conforme o tipo de aplicação:
  </p>

  <h4>Renda fixa (CDB, Tesouro, fundos de renda fixa)</h4>
  <p>
    O imposto segue a chamada tabela regressiva:
  </p>
  <ul>
    <li>Até 180 dias: 22,5%</li>
    <li>De 181 a 360 dias: 20%</li>
    <li>De 361 a 720 dias: 17,5%</li>
    <li>Acima de 720 dias: 15%</li>
  </ul>

  <p>
    Quanto mais tempo o dinheiro fica aplicado, menor é a porcentagem de imposto cobrada sobre o lucro.
  </p>

  <h4>Ações</h4>
  <p>
    Se a pessoa vender até R$ 20.000 por mês em ações, o lucro é isento.
    Acima desse valor, o imposto é:
  </p>
  <ul>
    <li>15% sobre o lucro em operações normais</li>
    <li>20% sobre o lucro em day trade</li>
  </ul>

  <h4>Fundos Imobiliários (FIIs)</h4>
  <ul>
    <li>Dividendos: geralmente isentos</li>
    <li>Lucro na venda: 20%</li>
  </ul>

  <h4>ETFs</h4>
  <ul>
    <li>15% sobre lucro em operações normais</li>
    <li>20% no day trade</li>
  </ul>

  <h3>Quando o imposto é pago</h3>
  <p>
    Em muitos investimentos de renda fixa, o imposto é descontado automaticamente no resgate.
    Já em ações, ETFs e FIIs, o investidor precisa calcular o imposto e pagar até o último dia útil do mês seguinte à venda, usando um DARF.
  </p>

  <h3>Como declarar os investimentos</h3>
  <p>
    Declarar investimentos envolve duas partes:
  </p>
  <ul>
    <li>Informar que você possui aquele investimento</li>
    <li>Informar se ele gerou lucro ou rendimento</li>
  </ul>

  <p>
    Normalmente, os investimentos são informados na ficha “Bens e Direitos”.
    Já os rendimentos aparecem nas fichas de “Rendimentos Tributáveis”, “Rendimentos Isentos”
    ou “Renda Variável”, dependendo do tipo de aplicação.
  </p>

  <p>
    Para preencher corretamente, o investidor precisa dos informes de rendimentos fornecidos por bancos e corretoras.
    Esses documentos mostram quanto foi investido, quanto rendeu e quanto de imposto foi pago.
  </p>

  <h3>Isenções de imposto</h3>
  <p>
    Existem situações em que não há cobrança de imposto:
  </p>
  <ul>
    <li>LCI e LCA (rendimento isento)</li>
    <li>Venda de ações até R$ 20.000 no mês</li>
    <li>Dividendos de ações</li>
    <li>Dividendos de FIIs, em regra</li>
  </ul>

  <p>
    Mesmo quando há isenção, o investimento precisa ser informado na declaração.
    Isento não significa invisível para a Receita Federal.
  </p>

  <h3>Por que declarar corretamente é importante</h3>
  <p>
    A Receita cruza informações com bancos, corretoras e empresas.
    Se houver diferença entre o que foi movimentado e o que foi declarado, o contribuinte pode cair na malha fina.
    Isso pode gerar multas, juros e muita dor de cabeça.
  </p>

  <p>
    Declarar corretamente também ajuda o próprio investidor a entender melhor sua vida financeira.
    Ao organizar os dados, fica mais fácil perceber quanto foi investido, quanto rendeu e quanto foi pago em impostos.
  </p>

  <p>
    Aprender a declarar investimentos é tão importante quanto aprender a investir.
    Quem domina as duas coisas tem mais controle, mais segurança e menos surpresas desagradáveis no futuro.
  </p>
