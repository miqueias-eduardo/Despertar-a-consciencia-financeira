  <h2>Quem investe precisa entender não só quanto ganha, mas quanto fica depois do imposto</h2>

  <h3>O que é Imposto de Renda</h3>
  <p>
    Imposto de Renda é um tributo cobrado pelo governo sobre os ganhos de uma pessoa.
    Ele não incide apenas sobre salários, mas também sobre lucros obtidos em aplicações financeiras.
  </p>
  <p>
    Quando você investe, o imposto não é calculado sobre o valor total aplicado, mas somente
    sobre o lucro obtido. Se alguém investe R$ 5.000 e, após certo período, passa a ter R$ 5.600,
    o imposto será calculado apenas sobre os R$ 600 que foram ganhos.
  </p>
  <p>
    Essa diferença é importante porque mostra que o imposto não “come” o dinheiro investido,
    mas apenas parte do crescimento que ele gerou.
  </p>

  <h3>Por que existe imposto sobre investimentos</h3>
  <p>
    O imposto sobre investimentos existe porque o lucro é considerado uma forma de renda.
    Assim como o salário é tributado, o ganho financeiro também é.
  </p>
  <p>
    Além disso, o sistema de impostos busca incentivar comportamentos mais estáveis, como
    investir por mais tempo e evitar movimentações apenas para ganhos rápidos.
  </p>

  <h3>O que é a tabela regressiva</h3>
  <p>
    A tabela regressiva é o modelo usado para calcular o Imposto de Renda em muitos investimentos.
    Ela recebe esse nome porque a porcentagem de imposto diminui conforme o tempo de aplicação aumenta.
  </p>
  <p>
    Isso significa que o governo cobra mais imposto de quem investe por pouco tempo e menos
    imposto de quem mantém o dinheiro investido por períodos maiores.
  </p>

  <h3>Percentuais da tabela regressiva no Brasil</h3>
  <p>
    Nos investimentos que seguem a tabela regressiva, o Imposto de Renda funciona da seguinte forma:
  </p>
  <ul>
    <li><strong>22,5%</strong> sobre o lucro para aplicações de até <strong>180 dias</strong></li>
    <li><strong>20%</strong> sobre o lucro para aplicações de <strong>181 a 360 dias</strong></li>
    <li><strong>17,5%</strong> sobre o lucro para aplicações de <strong>361 a 720 dias</strong></li>
    <li><strong>15%</strong> sobre o lucro para aplicações com mais de <strong>720 dias</strong></li>
  </ul>
  <p>
    Esses percentuais mostram que o tempo é um fator decisivo.
    Um investimento retirado rapidamente perde uma parte maior do lucro para o imposto.
    Já um investimento mantido por anos preserva mais do ganho.
  </p>

  <h3>Quanto tempo deixar o dinheiro para pagar menos imposto</h3>
  <p>
    Para atingir a menor faixa de imposto da tabela regressiva, o dinheiro precisa ficar
    investido por mais de 720 dias, ou seja, cerca de dois anos.
  </p>
  <p>
    Isso não quer dizer que todo investimento deve durar esse tempo, mas indica que aplicações
    de curto prazo tendem a ser menos vantajosas quando o imposto é considerado.
  </p>
  <p>
    Muitas vezes, dois investimentos parecem render o mesmo valor, mas aquele que ficou mais
    tempo aplicado acaba entregando mais dinheiro líquido, justamente por sofrer menos desconto.
  </p>

  <h3>Diferença entre investir e deixar o dinheiro parado</h3>
  <p>
    Quando o dinheiro fica parado, ele não gera lucro e, portanto, não sofre cobrança de imposto.
    No entanto, ele também não cresce e pode perder valor com o aumento dos preços.
  </p>
  <p>
    Quando o dinheiro é investido, ele passa a render. Esse rendimento é considerado ganho
    e, por isso, entra no cálculo do Imposto de Renda.
  </p>
  <p>
    Mesmo pagando imposto, o valor final costuma ser maior do que deixar o dinheiro sem render,
    desde que o investimento tenha sido bem escolhido.
  </p>

  <h3>Quando o imposto é cobrado</h3>
  <p>
    Na maior parte dos investimentos, o Imposto de Renda é cobrado apenas no momento do resgate.
    Enquanto o dinheiro está aplicado, não há desconto.
  </p>
  <p>
    Em muitos casos, o valor do imposto já é descontado automaticamente antes de o dinheiro
    entrar na conta do investidor. Em outros, o próprio investidor deve informar esses ganhos
    na declaração anual.
  </p>
  <p>
    Por isso, é essencial saber se o investimento escolhido já faz o desconto automático ou
    se será necessário recolher o imposto por conta própria.
  </p>

  <h3>Por que o imposto muda a forma de escolher investimentos</h3>
  <p>
    Avaliar apenas o rendimento bruto pode levar a decisões erradas.
    O que realmente importa é o rendimento líquido, ou seja, o que sobra depois do imposto.
  </p>
  <p>
    Um investimento que parece render mais pode acabar entregando menos dinheiro no final,
    caso fique pouco tempo aplicado e sofra uma alíquota maior.
  </p>
  <p>
    Quando o investidor entende essa lógica, passa a comparar investimentos de forma mais realista
    e a pensar no prazo antes de aplicar.
  </p>

  <h3>Conclusão do módulo</h3>
  <p>
    O Imposto de Renda é parte natural do processo de investir e obter lucro.
    Ele não impede o crescimento do dinheiro, mas influencia diretamente o resultado final.
  </p>
  <p>
    Quanto maior o tempo que o dinheiro permanece investido, menor tende a ser a parcela que
    vai para o imposto. Por isso, entender essas regras é tão importante quanto entender
    rentabilidade e liquidez.
  </p>

