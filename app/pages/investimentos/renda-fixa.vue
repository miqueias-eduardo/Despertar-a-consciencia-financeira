  <h1>Módulo 6 — Produtos de renda fixa</h1>
  <h2>Conhecendo os principais investimentos usados por quem busca estabilidade</h2>

  <p>
    Os investimentos de renda fixa recebem esse nome porque possuem regras de rendimento definidas
    no momento da aplicação. Isso não significa que o valor final é sempre exatamente igual,
    mas que o investidor já sabe de antemão como o dinheiro vai crescer.
  </p>
  <p>
    Em termos simples, investir em renda fixa é emprestar dinheiro para alguém e receber esse valor
    de volta no futuro com uma remuneração combinada. O que muda entre os produtos é
    quem recebe esse dinheiro, quanto tempo ele ficará emprestado e qual regra será usada para calcular o ganho.
  </p>

  <h3>6.1 — CDB e CDI</h3>
  <p>
    O CDB é um investimento em que a pessoa empresta dinheiro para um banco. Esse banco usa o valor
    para financiar suas atividades, como conceder empréstimos a outras pessoas ou empresas.
    Em troca, promete devolver o dinheiro com juros após um período.
  </p>
  <p>
    É parecido com quando alguém pede dinheiro emprestado e combina de devolver um pouco a mais depois.
    No CDB, esse “a mais” é o rendimento.
  </p>
  <p>
    O CDI é uma taxa usada como referência para esse tipo de investimento. Muitos CDBs informam
    que rendem um percentual do CDI. Isso significa que o rendimento acompanha, de forma aproximada,
    a taxa usada nas operações entre os próprios bancos.
  </p>
  <p>
    Um CDB pode permitir saque a qualquer momento ou exigir que o dinheiro fique parado até uma data específica.
    Por isso, antes de investir, é importante observar o prazo e as regras de resgate.
  </p>

  <h3>6.2 — Tesouro Direto</h3>
  <p>
    No Tesouro Direto, o dinheiro é emprestado ao governo. Esse valor é usado para manter serviços públicos,
    como estradas, escolas e hospitais. Em troca, o governo devolve o dinheiro com juros após um tempo.
  </p>
  <p>
    É como se o cidadão ajudasse a financiar o funcionamento do país e fosse recompensado por isso.
  </p>
  <p>
    Existem títulos diferentes dentro do Tesouro. Alguns têm rendimento definido desde o início,
    outros acompanham a inflação e outros acompanham taxas da economia. Cada um serve para um tipo de objetivo.
  </p>
  <p>
    O Tesouro é muito usado por quem quer aprender a investir, porque permite aplicar valores pequenos
    e possui regras claras sobre como o dinheiro vai crescer ao longo do tempo.
  </p>

  <h3>6.3 — LCI e LCA</h3>
  <p>
    LCI e LCA também funcionam como empréstimos ao banco, mas com um destino específico.
    O dinheiro aplicado é usado para financiar setores como o mercado imobiliário e o agronegócio.
  </p>
  <p>
    Na prática, a lógica é a mesma: o investidor empresta dinheiro, o banco utiliza esse valor nesses setores
    e depois devolve com juros.
  </p>
  <p>
    Uma característica importante desses investimentos é que, em muitos casos, o lucro recebido
    não sofre desconto de Imposto de Renda para pessoas físicas. Isso faz com que o ganho final
    possa ser interessante mesmo quando a taxa anunciada parece menor.
  </p>
  <p>
    Por outro lado, normalmente o dinheiro precisa ficar aplicado até o vencimento.
    Por isso, esse tipo de investimento exige planejamento, já que não costuma permitir saque antes do prazo.
  </p>

  <h3>6.4 — Fundos de renda fixa</h3>
  <p>
    Fundos de renda fixa funcionam como um investimento em grupo. Várias pessoas colocam dinheiro
    no mesmo fundo, e um gestor profissional usa esse valor para aplicar em diferentes produtos de renda fixa.
  </p>
  <p>
    É como juntar o dinheiro de muitas pessoas para formar uma carteira maior, com vários tipos de investimentos.
  </p>
  <p>
    O gestor segue regras definidas previamente e decide onde aplicar dentro do que o fundo permite,
    buscando equilíbrio entre rendimento e segurança.
  </p>
  <p>
    Esse tipo de fundo é escolhido por quem não quer decidir sozinho onde investir ou prefere delegar
    essa tarefa a um profissional. Em troca, existe cobrança de taxas, que reduzem o rendimento final.
  </p>

  <h3>Comparando os produtos de renda fixa</h3>
  <p>
    Apesar de diferentes, todos esses produtos seguem a mesma ideia básica: o dinheiro é emprestado
    e devolvido com rendimento. O que muda é quem recebe esse dinheiro e qual regra é usada para calcular os ganhos.
  </p>
  <ul>
    <li>no CDB, o dinheiro vai para o banco;</li>
    <li>no Tesouro, o dinheiro vai para o governo;</li>
    <li>na LCI e LCA, o dinheiro vai para setores específicos;</li>
    <li>nos fundos, o dinheiro é aplicado por um gestor.</li>
  </ul>

  <h3>Por que a renda fixa é importante para iniciantes</h3>
  <p>
    A renda fixa costuma ser o primeiro passo de quem começa a investir, porque ajuda a entender
    como funcionam conceitos como prazo, rendimento e resgate.
  </p>
  <p>
    Ela também é usada para guardar dinheiro que tem data para ser utilizado, como uma viagem,
    a compra de um bem ou uma reserva para imprevistos.
  </p>
  <p>
    Não é um tipo de investimento voltado para ganhos rápidos, mas sim para construção gradual
    de estabilidade financeira.
  </p>

  <h3>Conclusão do módulo</h3>
  <p>
    Produtos de renda fixa são diferentes formas de emprestar dinheiro e receber esse valor de volta
    com uma remuneração definida por regras claras.
  </p>
  <p>
    CDB, Tesouro, LCI, LCA e fundos de renda fixa atendem a objetivos distintos, mas todos ajudam
    a criar uma base mais organizada e previsível para quem investe.
  </p>
  <p>
    Entender esses produtos permite escolher melhor onde aplicar e evitar decisões tomadas no impulso.
  </p>

