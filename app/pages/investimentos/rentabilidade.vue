<section>

  <h1>Módulo 2 — Tipos de rentabilidade</h1>
  <h2>Depois de entender o que é investir, é hora de aprender como o dinheiro cresce</h2>

  <h3>O que é rentabilidade</h3>
  <p>
    Rentabilidade é o nome dado ao resultado que um investimento gera ao longo do tempo.
    Em termos simples, é o quanto o dinheiro aumenta depois que é aplicado.
  </p>
  <p>
    Quando alguém investe, não está apenas guardando dinheiro. Está colocando esse valor em
    algo que pode produzir ganhos. Esses ganhos podem ser maiores ou menores dependendo da
    forma como o investimento funciona.
  </p>
  <p>
    Existem diferentes maneiras de medir esse crescimento, e cada investimento segue um
    tipo de regra para definir quanto vai render. Essas regras são chamadas de tipos de
    rentabilidade.
  </p>

  <h3>O que é investimento pré-fixado</h3>
  <p>
    No investimento pré-fixado, o rendimento é conhecido desde o início. Antes mesmo de
    aplicar o dinheiro, a pessoa já sabe qual será o ganho se mantiver o investimento até o
    final do prazo combinado.
  </p>
  <p>
    Esse tipo de investimento funciona como um contrato: o valor do rendimento é definido
    no momento da aplicação e não muda depois disso.
  </p>
  <p>
    Ele costuma ser escolhido por quem gosta de previsibilidade e quer saber exatamente
    quanto terá no futuro. É muito usado quando a pessoa tem um objetivo com data marcada,
    como pagar um curso, uma viagem ou comprar algo planejado.
  </p>
  <p>
    A vantagem é a clareza do resultado. A desvantagem é que, se a economia mudar muito,
    esse rendimento pode ficar abaixo de outras opções disponíveis no mercado.
  </p>

  <h3>O que é investimento pós-fixado</h3>
  <p>
    No investimento pós-fixado, o valor do rendimento não é definido no começo. Ele depende
    de indicadores da economia que variam ao longo do tempo.
  </p>
  <p>
    Em vez de prometer um número fixo, esse tipo de investimento acompanha uma taxa que
    sobe e desce conforme a situação do país. Quando essa taxa aumenta, o rendimento cresce;
    quando diminui, o rendimento também cai.
  </p>
  <p>
    Esse modelo é muito usado para dinheiro que precisa estar disponível com facilidade,
    como uma reserva para emergências. Ele costuma ser mais estável e menos sensível a
    grandes variações de preço.
  </p>
  <p>
    O principal ponto desse tipo de investimento é acompanhar o ritmo da economia, sem
    prometer ganhos antecipados.
  </p>

  <h3>O que é investimento híbrido</h3>
  <p>
    O investimento híbrido combina duas formas de rendimento: uma parte fixa e outra parte
    variável, ligada a algum índice da economia.
  </p>
  <p>
    Funciona como um acordo em duas etapas: primeiro existe um ganho mínimo garantido;
    depois, existe um complemento que depende da variação de preços ou juros.
  </p>
  <p>
    Esse tipo de investimento é bastante usado quando a pessoa quer manter o poder de
    compra do dinheiro ao longo dos anos, evitando que ele perca valor com o aumento dos
    preços.
  </p>
  <p>
    Ele é mais comum em objetivos de longo prazo, pois foi pensado para proteger e aumentar
    o dinheiro com o passar do tempo.
  </p>

  <h3>O que são taxas: Selic, CDI e IPCA</h3>
  <p>
    Para entender como um investimento rende, é importante conhecer algumas taxas que
    servem como referência no mercado financeiro.
  </p>

  <p><strong>Selic</strong></p>
  <p>
    A Selic é a taxa básica de juros do país. Ela influencia empréstimos, financiamentos e
    diversos investimentos. Quando a Selic sobe, os rendimentos costumam aumentar; quando
    cai, os rendimentos tendem a diminuir.
  </p>

  <p><strong>CDI</strong></p>
  <p>
    O CDI é uma taxa muito próxima da Selic e é usada como base para vários investimentos.
    Quando um investimento promete render um percentual do CDI, significa que ele segue o
    comportamento dessa taxa.
  </p>

  <p><strong>IPCA</strong></p>
  <p>
    O IPCA é o índice que mede a inflação, ou seja, o aumento dos preços no dia a dia. Ele
    mostra se o dinheiro está perdendo valor com o tempo. Por isso, muitos investimentos de
    longo prazo usam o IPCA como referência, buscando preservar o poder de compra.
  </p>

  <h3>Como o rendimento é formado ao longo do tempo</h3>
  <p>
    O rendimento de um investimento não surge de uma vez. Ele se constrói aos poucos,
    conforme o tempo passa.
  </p>
  <p>
    Em vez de crescer em linha reta, o dinheiro tende a aumentar cada vez mais rápido,
    porque o rendimento também passa a render. Esse processo faz com que o crescimento seja
    maior no longo prazo do que no começo.
  </p>
  <p>
    Quanto mais tempo o dinheiro permanece investido, maior tende a ser o efeito desse
    crescimento. Por isso, investir por pouco tempo gera resultados pequenos, enquanto
    investir por mais tempo gera resultados mais expressivos.
  </p>
  <p>
    O mais importante não é decorar contas, mas entender que o tempo e a constância fazem
    diferença real no resultado final.
  </p>

  <h3>Por que entender os tipos de rentabilidade é essencial</h3>
  <p>
    Conhecer as formas de rendimento ajuda a escolher investimentos mais compatíveis com
    cada objetivo.
  </p>
  <ul>
    <li>quem precisa do dinheiro em breve tende a buscar previsibilidade;</li>
    <li>quem pensa no futuro pode aceitar mais variação;</li>
    <li>quem quer proteger o valor do dinheiro precisa considerar a inflação.</li>
  </ul>
  <p>
    Sem esse conhecimento, a pessoa aplica dinheiro sem saber o que esperar. Quando entende
    como funciona a rentabilidade, passa a investir com intenção e clareza.
  </p>

  <h3>Conclusão do módulo</h3>
  <p>
    Os investimentos podem render de maneiras diferentes: alguns mostram o resultado desde
    o início, outros acompanham a economia e outros misturam os dois modelos.
  </p>
  <p>
    Não existe um tipo melhor para todos. Existe o tipo mais adequado para cada objetivo e
    cada momento da vida.
  </p>

