  <p>
    O FGC, Fundo Garantidor de Créditos, funciona como um mecanismo de proteção para certos investimentos
    feitos em bancos. Ele existe para reduzir o prejuízo do cliente caso a instituição financeira
    enfrente problemas graves e não consiga devolver o dinheiro.
  </p>
