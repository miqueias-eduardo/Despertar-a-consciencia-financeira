    Quando investe por meio do governo, está emprestando dinheiro para o próprio país.
  </p>
  <p>
    A diferença está em quem assume a responsabilidade pelo pagamento.
    No banco, quem responde é a instituição financeira. No governo, quem responde é o Estado.
  </p>
  <p>
    Isso não significa que um seja sempre melhor que o outro. Significa que o tipo de risco é diferente.
